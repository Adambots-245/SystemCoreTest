package org.wpilib.schedulerlab;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.wpilib.command3.Command;
import org.wpilib.command3.Scheduler;
import org.wpilib.hardware.hal.HAL;
import org.wpilib.schedulerlab.mechanisms.Elevator;
import org.wpilib.schedulerlab.mechanisms.Wrist;

/**
 * Headless smoke tests for the Commands v3 scheduler behaviors the labs demonstrate. Runs the
 * default scheduler by hand — no robot loop, no NetworkTables, no hardware.
 */
class SchedulerSmokeTest {
  // Created once: each mechanism's constructor registers an idle default command with the default
  // scheduler, so per-test instances would pile up registrations.
  private static final Elevator elevator = new Elevator();
  private static final Wrist wrist = new Wrist();

  private final Scheduler scheduler = Scheduler.getDefault();

  @BeforeEach
  void setup() {
    assert HAL.initialize();
    scheduler.cancelAll();
  }

  private void runCycles(int n) {
    for (int i = 0; i < n; i++) {
      scheduler.run();
    }
  }

  @Test
  void moveToRunsAcrossCyclesAndCompletes() {
    Command move = elevator.moveTo(1.0);
    assertInstanceOf(Scheduler.ScheduleResult.Success.class, scheduler.schedule(move));

    runCycles(2);
    assertTrue(scheduler.isRunning(move), "moveTo should still be running after 2 cycles");

    runCycles(100); // 1.0 m at 0.02 m/cycle = 50 cycles
    assertFalse(scheduler.isScheduledOrRunning(move), "moveTo should have completed");
    assertTrue(elevator.atGoal(1.0), "elevator should be at goal");
    assertFalse(
        elevator.getRunningCommands().isEmpty(),
        "the idle default command should have resumed on the elevator");
  }

  @Test
  void equalOrHigherPriorityInterruptsRunningCommand() {
    Command low = elevator.holdAt(0.3, -10, "LowHold");
    scheduler.schedule(low);
    runCycles(1);
    assertTrue(scheduler.isRunning(low));

    Command normal = elevator.moveTo(0.5);
    assertInstanceOf(Scheduler.ScheduleResult.Success.class, scheduler.schedule(normal));
    runCycles(1);
    assertFalse(scheduler.isScheduledOrRunning(low), "low-priority hold should be interrupted");
    assertTrue(scheduler.isRunning(normal));
  }

  @Test
  void lowerPriorityIsRejectedAtScheduleTime() {
    Command high = elevator.holdAt(1.8, 10, "HighHold");
    scheduler.schedule(high);
    runCycles(1);

    var result =
        assertInstanceOf(
            Scheduler.ScheduleResult.LowerPriorityThanRunningCommand.class,
            scheduler.schedule(elevator.moveTo(0.5)));
    assertEquals(high, result.alreadyRunning(), "the rejection should name the blocking command");

    scheduler.cancel(high);
    assertFalse(scheduler.isScheduledOrRunning(high));
  }

  @Test
  void parallelGroupRejectsSharedRequirements() {
    assertThrows(
        IllegalArgumentException.class,
        () -> Command.parallel(elevator.moveTo(1.0), elevator.moveTo(0.0)).withAutomaticName());
  }

  @Test
  void sequenceGetsAutoGeneratedName() {
    Command seq = Command.sequence(elevator.moveTo(1.0), elevator.moveTo(0.0)).withAutomaticName();
    assertTrue(seq.name().contains("->"), "auto name should join steps, got: " + seq.name());
  }

  @Test
  void forkedChildrenDieWithTheirParent() {
    Command parent =
        Command.noRequirements(
                co -> {
                  co.fork(wrist.sweep());
                  co.park();
                })
            .named("Parent");
    scheduler.schedule(parent);
    runCycles(2);
    assertTrue(
        wrist.getRunningCommands().stream().anyMatch(c -> c.name().equals("Wrist.sweep")),
        "forked sweep should be running under the parent");

    scheduler.cancel(parent);
    assertTrue(
        wrist.getRunningCommands().stream().noneMatch(c -> c.name().equals("Wrist.sweep")),
        "canceling the parent must cancel its forked children");
  }
}
